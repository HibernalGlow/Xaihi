/**
 * 生成 `packages/cli/src/node-cli-registry.generated.ts`：聚合 CLI 的节点命令表。
 *
 * 为什么这必须由脚本生成：那份文件在上游是 `scripts/generate-node-registries.ts` 的产物，
 * 我们把它整份搬过来时一并带了 **46 条**条目，而本仓真正存在的节点包只有 `plugins/*` 那些。
 * `packages/cli/src/index.ts:200` 是按 `${packageName}/cli` 动态 import 的，
 * 所以每一条不存在的条目都是一个"帮助里印得出来、跑起来 module not found"的假承诺
 * （与 `docs/service-mapping.md` 的 G7 同一类：面在宣传兑现不了的入口）。
 * 上游那份生成器不在本仓，因此**生产者必须在这里**，不然生成物就是手改一次的死文件。
 *
 * 输入只有一个真相源：各 `plugins/<id>/package.json` 的 `name` / `bin` / `exports["./cli"]`
 * 与 `xaihi.node` 的 `description.en`。三条都得齐，缺一就不进表（不是回退成猜测）。
 *
 * 用法：
 *   node scripts/gen-cli-registry.mjs            # 写
 *   node scripts/gen-cli-registry.mjs --check     # 判据：盘上的那份必须等于现在该生成的
 *   node scripts/gen-cli-registry.mjs --self-check# 阳性对照：漏一条判据这把尺必须红
 */

import { readdirSync, readFileSync, existsSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const PLUGINS = join(ROOT, 'plugins')
const TARGET = join(ROOT, 'packages/cli/src/node-cli-registry.generated.ts')

/** 一个候选节点包必须齐的三样；`description` 取清单的 `description.en`，缺则用 `title.en`。 */
export function registryEntries(pluginsDir = PLUGINS) {
  const out = []
  for (const dir of readdirSync(pluginsDir, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue
    const manifestPath = join(pluginsDir, dir.name, 'package.json')
    if (!existsSync(manifestPath)) continue
    const pkg = JSON.parse(readFileSync(manifestPath, 'utf8'))
    const binName = Object.keys(pkg.bin ?? {})[0]
    if (typeof binName !== 'string' || typeof pkg.name !== 'string') continue
    const exports_ = pkg.exports ?? {}
    if (exports_['./cli'] === undefined || exports_['./help'] === undefined) continue
    const node = pkg.xaihi?.node ?? {}
    const description = node?.description?.en ?? node?.title?.en ?? ''
    if (description.length === 0) continue
    out.push({ id: dir.name, packageName: pkg.name, bin: binName, description: `${description}`.replace(/\s+/g, ' ').trim() })
  }
  return out.sort((left, right) => left.id.localeCompare(right.id))
}

export function render(entries) {
  const body = entries.map((entry) =>
    `  {\n    id: ${JSON.stringify(entry.id)},\n    packageName: ${JSON.stringify(entry.packageName)},\n    bin: ${JSON.stringify(entry.bin)},\n    description: ${JSON.stringify(entry.description)},\n  },`).join('\n')
  return `// Generated by scripts/gen-cli-registry.mjs. Do not edit by hand.\n`
    + `// 表里只有本仓真的存在、且真的带 bin 与 ./cli ./help 两条导出的节点包；\n`
    + `// 上游那份 46 条的清单里，没有对应物的条目一律不进（见本文件脚本头的说明）。\n\n`
    + `export const GENERATED_NODE_CLI_REGISTRY = [\n${body}\n]\n`
}

const POSITIVE_CONTROL_FIXTURE = [
  { id: 'alpha', packageName: '@hibernalglow/xaihi-alpha', bin: 'xalpha', description: 'Alpha node.' },
]

if (process.argv.includes('--self-check')) {
  const problems = []
  const rendered = render(POSITIVE_CONTROL_FIXTURE)
  if (!rendered.includes('"xalpha"')) problems.push('渲染器没把 bin 写出来 ⇒ 这张尺看不见条目本身')
  if (rendered.includes('@xiranite/node-')) problems.push('渲染器还在写上游包名 ⇒ 生成的表会指向不存在的包')
  if (render(POSITIVE_CONTROL_FIXTURE) === render([])) problems.push('空表与非空表渲染结果相同 ⇒ 条数这条判据是假的')
  if (registryEntries(PLUGINS).length === 0) problems.push('现读到的条目数为 0 ⇒ plugins/ 里没有带 bin 的包，这把尺没东西可量')
  for (const problem of problems) console.error(`  × ${problem}`)
  process.exit(problems.length > 0 ? 1 : 0)
}

const entries = registryEntries()
const next = render(entries)

if (process.argv.includes('--check')) {
  const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : ''
  if (current !== next) {
    console.error(`gen-cli-registry --check: 盘上的表与现读不一致（现读 ${entries.length} 条）。跑 \`node scripts/gen-cli-registry.mjs\` 再生成`)
    process.exit(1)
  }
  console.log(`gen-cli-registry --check OK（${entries.length} 条，逐条来自 plugins/*/package.json 的 bin + ./cli + ./help）`)
  process.exit(0)
}

writeFileSync(TARGET, next)
console.log(`gen-cli-registry: 写了 ${TARGET.replace(`${ROOT}/`, '')}（${entries.length} 条：${entries.map((entry) => entry.id).join(', ')}）`)
